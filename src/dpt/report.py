def _begin(name: str) -> str:
    return f"<!-- BEGIN {name} (generated by python -m dpt.run_all; do not edit) -->"


def _end(name: str) -> str:
    return f"<!-- END {name} -->"


def update_blocks(path: Path, blocks: dict[str, str]) -> None:
    """Replace the text between each block's BEGIN / END markers in ``path``."""
    text = path.read_text(encoding="utf-8")
    for name, body in blocks.items():
        a, b = _begin(name), _end(name)
        if a not in text or b not in text:
            raise ValueError(f"{path.name}: markers for block {name!r} not found")
        i, j = text.index(a), text.index(b) + len(b)
        text = text[:i] + f"{a}\n\n{body.strip()}\n\n{b}" + text[j:]
    path.write_text(text, encoding="utf-8", newline="\n")


# --------------------------------------------------------------------------- helpers
def _n(v: float | None, nd: int = 0) -> str:
    """Number with ``nd`` decimals, ``n/a`` for missing values."""
    if v is None or math.isnan(v):
        return "n/a"
    return f"{v:.{nd}f}"


def _pct(v: float | None) -> str:
    """Signed percentage, ``n/a`` for missing values."""
    if v is None or math.isnan(v):
        return "n/a"
    if abs(v) < 0.5:
        return "0 %"
    return f"{v:+.0f} %"


def _table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _validation_rows(s: Summary) -> list[dict[str, Any]]:
    part = NOMINAL.device.part
    return [r for r in s["validation"] if r["part"] == part and not r["error"]]


def _nominal_validation(s: Summary) -> dict[str, Any]:
    return next(r for r in _validation_rows(s) if r["l_loop_nH"] == round(NOMINAL.l_loop * 1e9, 6))


def _budget(s: Summary, prefix: str) -> dict[str, Any]:
    return next(r for r in s["error_budget"] if r["source"].startswith(prefix))


def _rg_off_row(s: Summary, rg: float) -> dict[str, Any]:
    return next(r for r in s["rg"]["rg_off_rows"] if r["rg"] == rg)


