def validation_block(s: Summary) -> str:
    v = _validation_rows(s)
    p = next(d for d in DATASHEET_POINTS if d.device.part == NOMINAL.device.part)
    vt = _table(
        [
            "Loop L",
            "Eon sim / ds (µJ)",
            "Eon dev.",
            "Eoff sim / ds (µJ)",
            "Eoff dev.",
            "Eon + Eoff sim / ds (µJ)",
            "Eon + Eoff dev.",
        ],
        [
            [
                f"{r['l_loop_nH']:g} nH",
                f"{_n(r['e_on_sim_uJ'])} / {_n(r['e_on_ds_uJ'])}",
                _pct(r["e_on_dev_pct"]),
                f"{_n(r['e_off_sim_uJ'])} / {_n(r['e_off_ds_uJ'])}",
                _pct(r["e_off_dev_pct"]),
                f"{_n(r['e_tot_sim_uJ'])} / {_n(r['e_tot_ds_uJ'])}",
                _pct(r["e_tot_dev_pct"]),
            ]
            for r in v
        ],
    )
    bt = _table(
        ["Input changed from the nominal set-up", "How", "Eon", "Eoff", "Eon + Eoff"],
        [
            [
                r["source"],
                r["method"],
                _pct(r["e_on_change_pct"]),
                _pct(r["e_off_change_pct"]),
                _pct(r["e_tot_change_pct"]),
            ]
            for r in s["error_budget"][1:]
        ],
    )
    nom = _nominal_validation(s)
    drv = _budget(s, "Driver output resistance")
    late = _budget(s, "Current probe 1 ns late")
    sh, ct = EVB_TABLE4["shunt"], EVB_TABLE4["current transformer"]
    evb_tot = 100.0 * ((ct[0] + ct[1]) - (sh[0] + sh[1])) / (sh[0] + sh[1])
    text = (
        f"Datasheet condition: {p.vbus:.0f} V, {p.i_load:.0f} A, Rg = {p.rg:g} Ω, "
        f"-3 V / +18 V, {p.temp:.0f} °C, body diode of the same part as free-wheeler "
        f"({p.source.split(',')[0]}).\n\n{vt}\n\n"
        "**Error budget at the nominal point** (change of each quantity relative to the "
        "nominal simulation):\n\n"
        f"{bt}\n\n"
        f"How to read it. No single input above closes the {_pct(nom['e_off_dev_pct'])} "
        "Eoff gap on its own. Two things the ideal set-up lacks each move Eoff by a large "
        f"part of it: 1 Ω of driver output resistance raises Eoff by "
        f"{_pct(drv['e_off_change_pct'])} (the swept Rg,off reproduces the datasheet Eoff "
        f"at about {_n(s['rg_off_matching_datasheet_eoff'], 1)} Ω instead of "
        f"{NOMINAL.rg_off:g} Ω), and a current probe 1 ns late raises the measured Eoff by "
        f"{_pct(late['e_off_change_pct'])}. Together they would account for the gap, but "
        "neither can be confirmed without the datasheet bench. The deskew error also "
        f"lowers Eon ({_pct(late['e_on_change_pct'])}) and leaves Eon + Eoff almost "
        f"unchanged ({_pct(late['e_tot_change_pct'])}): timing errors shift energy between "
        "the two edges. onsemi's own DPT board manual shows the same on hardware: changing only "
        f"the current sensor moved Eon from {sh[0]:.0f} to {ct[0]:.0f} µJ and Eoff from "
        f"{sh[1]:.0f} to {ct[1]:.0f} µJ, while Eon + Eoff changed by {evb_tot:+.0f} % "
        "(EVBUM2897/D, Table 4; 600 V, Rg = 3.9 Ω). Eon + Eoff is therefore the more "
        "trustworthy comparison, and the loop inductance, which the datasheet does not "
        "state, is the largest single unknown."
    )
    return text


def takeaways(s: Summary) -> str:
    rg, sb, k, lim = s["rg"], s["stray_budget"], s["kelvin"], s["limits"]
    on_rows = {r["rg"]: r for r in rg["rg_on_rows"]}
    flat = [on_rows[x]["on_e_on"] + on_rows[x]["on_e_rr"] for x in (1.0, 2.2, 4.5)]
    vpk = f"{_n(lim['v_peak_limit_V'])} V"
    dvl = f"{_n(lim['dv_dt_limit_V_per_ns'])} V/ns"
    vth = lim["vth_min_V"]
    bullets = []
    on_pk = rg["rg_on_best_peak_only"]
    bullets.append(
        "**Rg,on.** Eon + Err stays between "
        f"{_n(min(flat) * UJ)} and {_n(max(flat) * UJ)} µJ from 1 Ω to 4.5 Ω: a faster "
        "turn-on lowers Eon but raises the free-wheeling device's recovery energy by "
        "almost as much. "
        + (
            f"Keeping its recovery overshoot ≤ {vpk} needs Rg,on ≥ {on_pk:g} Ω. "
            if on_pk is not None
            else f"No swept Rg,on keeps its recovery overshoot ≤ {vpk}. "
        )
        + (
            f"No swept Rg,on meets {dvl} peak dv/dt (lowest {_n(rg['rg_on_lowest_dvdt'])} "
            f"V/ns at {rg['rg_on_lowest_dvdt_at']:g} Ω): the last part of the vDS fall is the "
            "fast collapse at the end of the body-diode recovery (visible in the turn-on "
            "waveform), so the lever is the free-wheeling device or a snubber, not more "
            "gate resistance."
            if rg["rg_on_best_both"] is None
            else f"Rg,on = {rg['rg_on_best_both']:g} Ω meets both limits at the lowest loss."
        )
    )
    if rg["rg_off_best_both"] is not None:
        best = _rg_off_row(s, rg["rg_off_best_both"])
        nom = _rg_off_row(s, NOMINAL.rg_off)
        bullets.append(
            f"**Rg,off.** Meeting {dvl} at turn-off with every peak ≤ {vpk} needs "
            f"Rg,off ≥ {rg['rg_off_best_both']:g} Ω. Eoff alone rises from "
            f"{_n(nom['off_e_off'] * UJ)} to {_n(best['off_e_off'] * UJ)} µJ, but Eon + "
            f"Eoff + Err rises from {_n(nom['e_cycle'] * UJ)} to "
            f"{_n(best['e_cycle'] * UJ)} µJ: the free-wheeling device is held off "
            "through the same resistor, and its gate is pulled up to "
            f"{_n(best['on_vgs_hs_max'], 1)} V (VGS(th),min = {vth:.2f} V) during the DUT "
            f"turn-on, so it conducts briefly (its terminal Qrr rises from "
            f"{_n(nom['on_q_rr'] * 1e9)} to {_n(best['on_q_rr'] * 1e9)} nC). "
            "A resistor-only design that limits dv/dt "
            "this way pays mainly in shoot-through; a separate low-impedance hold-off "
            "path (Miller clamp) is needed."
        )
    else:
        bullets.append(f"**Rg,off.** No swept Rg,off meets {dvl} with every peak ≤ {vpk}.")
    vg = s["vgs_off"]
    nom_vg = next(r for r in vg if r["vgs_off"] == NOMINAL.vgs_off)
    safe = [r for r in vg if r["margin"] > 0]
    off_txt = (
        f"**Off-state bias.** At {NOMINAL.vgs_off:g} V the free-wheeling device's gate "
        f"reaches {_n(nom_vg['vgs_hs_max'], 2)} V during DUT turn-on, above VGS(th),min = "
        f"{vth:.2f} V. "
    )
    if safe:
        r = max(safe, key=lambda x: float(x["vgs_off"]))
        off_txt += (
            f"{r['vgs_off']:g} V restores a {r['margin']:+.2f} V margin (Err "
            f"{_n(nom_vg['e_rr_uJ'])} → {_n(r['e_rr_uJ'])} µJ), "
            + (
                f"but the gate then undershoots to {_n(r['vgs_hs_min'], 2)} V at DUT "
                f"turn-off, beyond the {lim['vgs_abs_min_V']:g} V rating. Bias alone "
                "does not fix it; an active Miller clamp is the next thing to simulate."
                if r["vgs_hs_min"] < lim["vgs_abs_min_V"]
                else "with the undershoot inside the gate rating."
            )
        )
    bullets.append(off_txt)
    bullets.append(
        f"**Stray inductance.** Every vDS peak stays ≤ {vpk} up to "
        f"{_n(sb['l_max_nH_both'], 1)} nH of external loop inductance. The free-wheeling "
        f"device's recovery overshoot sets that limit; the DUT turn-off peak alone would "
        f"allow {_n(sb['l_max_nH_turn_off'], 1)} nH, so a layout review that only checks "
        "the DUT turn-off spike accepts a loop that overstresses the other device."
    )
    pkg = next(r for r in k["rows"] if r["l_cs_nH"] == 0.0)
    eq = k["equal_didt"]
    unstable = [r for r in k["rows"] if not r["gate_ok"]]
    bullets.append(
        "**Kelvin source.** Returning the driver to the power source pin puts the "
        "package source inductance into the gate loop: at equal Rg, Eon + Eoff rises "
        f"by {pkg['e_ts_increase_pct']:.0f} % and Eon + Eoff + Err by "
        f"{pkg['e_cycle_increase_pct']:.0f} % (the slower turn-on lowers Err). Equal Rg is "
        "not equal speed, though: against a Kelvin-driven DUT slowed to the same turn-on "
        f"di/dt ({_n(eq['di_dt_A_per_ns'], 2)} A/ns, Rg,on ≈ {_n(eq['kelvin_rg_on'], 1)} Ω), "
        f"the Eon penalty is {eq['e_on_increase_pct']:.0f} % instead of "
        f"{k['non_kelvin_e_on_increase_pct']:.0f} %."
        + (
            f" With {unstable[0]['l_cs_nH']:g} nH of extra shared inductance the gate loop "
            "oscillates beyond the gate rating."
            if unstable
            else ""
        )
    )
    return "\n".join(f"- {b}" for b in bullets)


def readme_blocks(s: Summary) -> dict[str, str]:
    return {"headline": headline(s), "validation": validation_block(s), "takeaways": takeaways(s)}


