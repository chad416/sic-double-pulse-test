"""Reproduce every result of the project with one command.

    python -m dpt.run_all            # simulate (cached), analyse, plot, update README
    python -m dpt.run_all --workers 2

Outputs
-------
results/*.csv           one row per simulation (configuration + all extracted metrics)
results/summary.json    the headline numbers quoted in the README
docs/figures/*.png      every figure in the README
README.md               the block between the RESULTS markers is regenerated
"""

