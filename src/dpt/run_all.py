def _kelvin_row(r: dict[str, object]) -> list[str]:
    vg = f"{r['vgs_min']:.0f} … {r['vgs_max']:.0f}"
    if not r["gate_ok"]:
        return [f"{r['l_cs_nH']:.0f}", "–", "–", "–", "–", f"**{vg}: gate loop oscillates**"]
    return [
        f"{r['l_cs_nH']:.0f}",
        f"{r['e_on_uJ']:.0f}",
        f"{r['e_off_uJ']:.0f}",
        f"{r['e_ts_uJ']:.0f}",
        f"{r['e_ts_increase_pct']:+.0f} %",
        vg,
    ]


