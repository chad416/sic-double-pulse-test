def _validation_figure(val_rows: list[Row]) -> None:
    rows = []
    for p in DATASHEET_POINTS:
        sel = [
            r
            for r in val_rows
            if r["part"] == p.device.part and r["temp"] == p.temp and not r["error"]
        ]
        if not sel:
            continue
        ls = [float(r["l_loop_nH"]) for r in sel]  # type: ignore[arg-type]
        title = f"{p.device.part}, {p.vbus:.0f} V / {p.i_load:.0f} A, {p.temp:.0f} C"
        x = "External loop inductance (nH)"
        e_on = [float(r["e_on_sim_uJ"]) for r in sel]  # type: ignore[arg-type]
        e_off = [float(r["e_off_sim_uJ"]) for r in sel]  # type: ignore[arg-type]
        rows.append(
            [
                Panel(
                    ls,
                    x,
                    "Eon (uJ)",
                    [("simulated", e_on)],
                    (p.e_on * UJ, "datasheet typ."),
                    title=title,
                ),
                Panel(
                    ls,
                    x,
                    "Eoff (uJ)",
                    [("simulated", e_off)],
                    (p.e_off * UJ, "datasheet typ."),
                    title=title,
                ),
            ]
        )
    plots.panel_grid(
        rows,
        "Validation: simulated vs datasheet switching energy (datasheet loop L not published)",
        FIGURES / "validation.png",
    )


def _rg_tradeoff(sw: dict[str, tuple[Sweep, list[RunRecord]]], summary: Row) -> None:
    dev = NOMINAL.device
    v_lim = V_PEAK_LIMIT_FRACTION * dev.vds_rating
    lim_v = (v_lim, f"{V_PEAK_LIMIT_FRACTION:.0%} of V(BR)DSS")
    lim_dv = (DVDT_LIMIT * VNS, "dv/dt limit")
    ok_on, ok_off = _ok(sw["rg_on"][1]), _ok(sw["rg_off"][1])
    x_on = [r.cfg.rg_on for r in ok_on]
    x_off = [r.cfg.rg_off for r in ok_off]
    # Peak dv/dt (1 ns window) is used for the EMI limit: the turn-on vDS fall has a slow
    # L*di/dt part and a fast diode-recovery collapse, so a 20-80 % average misleads.
    dv_on = _col(ok_on, "on_dv_dt_max", VNS)
    dv_off = _col(ok_off, "off_dv_dt_max", VNS)
    xo, xf = "Rg,on (Ohm)", "Rg,off (Ohm)"
    plots.panel_grid(
        [
            [
                Panel(
                    x_on,
                    xo,
                    "Energy (uJ)",
                    [("Eon", _col(ok_on, "on_e_on", UJ)), ("Err", _col(ok_on, "on_e_rr", UJ))],
                    xlog=True,
                    title="Turn-on (Rg,off = 4.5 Ohm)",
                ),
                Panel(x_on, xo, "Peak |dv/dt|, turn-on (V/ns)", [("dv/dt", dv_on)], lim_dv, True),
                Panel(
                    x_on,
                    xo,
                    "Free-wheel peak vDS (V)",
                    [("peak", _col(ok_on, "on_vds_hs_peak"))],
                    lim_v,
                    True,
                ),
                Panel(
                    x_on,
                    xo,
                    "Free-wheel vGS peak (V)",
                    [("peak", _col(ok_on, "on_vgs_hs_max"))],
                    (dev.vth_min, "VGS(th) min"),
                    True,
                ),
            ],
            [
                Panel(
                    x_off,
                    xf,
                    "Energy (uJ)",
                    [("Eoff", _col(ok_off, "off_e_off", UJ))],
                    xlog=True,
                    title="Turn-off (Rg,on = 4.5 Ohm)",
                ),
                Panel(
                    x_off, xf, "Peak |dv/dt|, turn-off (V/ns)", [("dv/dt", dv_off)], lim_dv, True
                ),
                Panel(
                    x_off,
                    xf,
                    "DUT peak vDS (V)",
                    [("peak", _col(ok_off, "off_vds_peak"))],
                    lim_v,
                    True,
                ),
                Panel(
                    x_off,
                    xf,
                    "Free-wheel vGS minimum (V)",
                    [("min", _col(ok_off, "off_vgs_hs_min"))],
                    (-10.0, "VGS abs. min (-10 V)"),
                    True,
                ),
            ],
        ],
        f"{dev.part}: gate-resistor trade-off at 800 V / 40 A, 30 nH",
        FIGURES / "rg_tradeoff.png",
    )
    i_on = best_under_constraints(
        x_on,
        _col(ok_on, "on_e_on"),
        [
            [v <= DVDT_LIMIT * VNS for v in dv_on],
            [v <= v_lim for v in _col(ok_on, "on_vds_hs_peak")],
        ],
    )
    i_off = best_under_constraints(
        x_off,
        _col(ok_off, "off_e_off"),
        [
            [v <= DVDT_LIMIT * VNS for v in dv_off],
            [v <= v_lim for v in _col(ok_off, "off_vds_peak")],
        ],
    )

    def first_ok(xs: list[float], ok: list[bool]) -> float | None:
        """Smallest swept Rg from which the constraint holds for every larger Rg."""
        for i in range(len(xs)):
            if all(ok[i:]):
                return xs[i]
        return None

    pk_on_l, pk_off_l = _col(ok_on, "on_vds_hs_peak"), _col(ok_off, "off_vds_peak")
    summary["rg_min"] = {
        "on_peak": first_ok(x_on, [v <= v_lim for v in pk_on_l]),
        "on_dvdt": first_ok(x_on, [v <= DVDT_LIMIT * VNS for v in dv_on]),
        "on_dvdt_lowest": min(dv_on),
        "off_peak": first_ok(x_off, [v <= v_lim for v in pk_off_l]),
        "off_dvdt": first_ok(x_off, [v <= DVDT_LIMIT * VNS for v in dv_off]),
    }
    on_keys = (
        "on_e_on",
        "on_e_rr",
        "on_dv_dt",
        "on_dv_dt_max",
        "on_vds_hs_peak",
        "on_vgs_hs_max",
    )
    off_keys = ("off_e_off", "off_dv_dt", "off_dv_dt_max", "off_vds_peak", "off_vgs_hs_min")
    # Rg,off that would reproduce the datasheet Eoff (linear interpolation in the sweep).
    ds_eoff = next(p.e_off for p in DATASHEET_POINTS if p.device.part == NOMINAL.device.part)
    e_off_curve = _col(ok_off, "off_e_off")
    summary["rg_off_matching_datasheet_eoff"] = float(np.interp(ds_eoff, e_off_curve, x_off))
    summary["rg_choice"] = {
        "rg_on": x_on[i_on] if i_on is not None else None,
        "rg_off": x_off[i_off] if i_off is not None else None,
        "rule": "lowest loss with |dv/dt| <= limit and every vDS peak <= limit",
        "rg_on_rows": [
            {"rg": x, **{k: r.metrics[k] for k in on_keys}}
            for x, r in zip(x_on, ok_on, strict=True)
        ],
        "rg_off_rows": [
            {"rg": x, **{k: r.metrics[k] for k in off_keys}}
            for x, r in zip(x_off, ok_off, strict=True)
        ],
    }


def _stray_budget(sw: dict[str, tuple[Sweep, list[RunRecord]]], summary: Row) -> None:
    dev = NOMINAL.device
    v_lim = V_PEAK_LIMIT_FRACTION * dev.vds_rating
    ok = _ok(sw["l_loop"][1])
    xl = [round(r.cfg.l_loop / NH, 6) for r in ok]
    pk_off, pk_on = _col(ok, "off_vds_peak"), _col(ok, "on_vds_hs_peak")
    x = "External loop inductance (nH)"
    plots.panel_grid(
        [
            [
                Panel(
                    xl,
                    x,
                    "Peak vDS (V)",
                    [("DUT at turn-off", pk_off), ("Free-wheel at turn-on", pk_on)],
                    (v_lim, f"{V_PEAK_LIMIT_FRACTION:.0%} of V(BR)DSS"),
                ),
                Panel(
                    xl,
                    x,
                    "Energy (uJ)",
                    [("Eon", _col(ok, "on_e_on", UJ)), ("Eoff", _col(ok, "off_e_off", UJ))],
                ),
                Panel(xl, x, "Turn-off ringing (MHz)", [("f_ring", _col(ok, "off_f_ring", 1e-6))]),
            ]
        ],
        f"{dev.part}: stray-inductance budget at 800 V / 40 A, Rg = 4.5 Ohm",
        FIGURES / "stray_budget.png",
    )
    worst = [max(a, b) for a, b in zip(pk_off, pk_on, strict=True)]
    summary["stray_budget"] = {
        "l_max_nH_turn_off": max_x_below(xl, pk_off, v_lim),
        "l_max_nH_turn_on_freewheel": max_x_below(xl, pk_on, v_lim),
        "l_max_nH_both": max_x_below(xl, worst, v_lim),
        "rows": [
            {"l_nH": a, "pk_off": b, "pk_on": c, "f_ring_MHz": r.metrics["off_f_ring"] * 1e-6}
            for a, b, c, r in zip(xl, pk_off, pk_on, ok, strict=True)
        ],
    }


def _kelvin(
    sw: dict[str, tuple[Sweep, list[RunRecord]]], kel: dict[str, float], summary: Row
) -> None:
    dev = NOMINAL.device
    ok = _ok(sw["l_cs"][1])
    xk = [round(r.cfg.l_cs / NH, 6) for r in ok]
    x = "Extra common-source inductance (nH)"
    # Only gate-stable runs carry a meaningful loss value; oscillating ones are listed
    # in the README table instead of being plotted as if they were valid points.
    st = [r for r in ok if r.metrics.get("gate_ok", 0.0) == 1.0]
    xs = [round(r.cfg.l_cs / NH, 6) for r in st]
    n_bad = len(ok) - len(st)
    kel_line = "Kelvin drive"
    plots.panel_grid(
        [
            [
                Panel(
                    xs,
                    x,
                    "Eon (uJ)",
                    [("non-Kelvin", _col(st, "on_e_on", UJ))],
                    (kel["on_e_on"] * UJ, kel_line),
                ),
                Panel(
                    xs,
                    x,
                    "Eoff (uJ)",
                    [("non-Kelvin", _col(st, "off_e_off", UJ))],
                    (kel["off_e_off"] * UJ, kel_line),
                ),
                Panel(
                    xs,
                    x,
                    "Eon + Eoff (uJ)",
                    [("non-Kelvin", _col(st, "e_ts", UJ))],
                    (kel["e_ts"] * UJ, kel_line),
                ),
            ]
        ],
        f"{dev.part}: Kelvin-source benefit at 800 V / 40 A, Rg = 4.5 Ohm, 30 nH"
        + (
            f" ({n_bad} larger-Lcs run omitted: gate loop oscillates beyond rating)"
            if n_bad
            else ""
        ),
        FIGURES / "kelvin_benefit.png",
    )
    summary["kelvin"] = {
        "kelvin_e_on_uJ": kel["on_e_on"] * UJ,
        "kelvin_e_off_uJ": kel["off_e_off"] * UJ,
        "kelvin_e_ts_uJ": kel["e_ts"] * UJ,
        "rows": [
            {
                "l_cs_nH": x_,
                "e_on_uJ": r.metrics["on_e_on"] * UJ,
                "e_off_uJ": r.metrics["off_e_off"] * UJ,
                "e_ts_uJ": r.metrics["e_ts"] * UJ,
                "e_ts_increase_pct": deviation_pct(r.metrics["e_ts"], kel["e_ts"]),
                "vgs_max": max(r.metrics["on_vgs_max"], r.metrics["off_vgs_max"]),
                "vgs_min": min(r.metrics["on_vgs_min"], r.metrics["off_vgs_min"]),
                "gate_ok": bool(r.metrics["gate_ok"]),
            }
            for x_, r in zip(xk, ok, strict=True)
        ],
    }


def _operating_point(sw: dict[str, tuple[Sweep, list[RunRecord]]], summary: Row) -> None:
    panels = []
    for name, label in (
        ("i_load", "Switched current at turn-off (A)"),
        ("vbus", "DC-link voltage (V)"),
        ("temp", "Temperature (C)"),
    ):
        s, recs = sw[name]
        ok = _ok(recs)
        xs = [r.metrics["i_off"] if name == "i_load" else getattr(r.cfg, s.param) for r in ok]
        series = [
            ("Eon", _col(ok, "on_e_on", UJ)),
            ("Eoff", _col(ok, "off_e_off", UJ)),
            ("Err", _col(ok, "on_e_rr", UJ)),
        ]
        panels.append(Panel(xs, label, "Energy (uJ)", series))
        summary[f"sweep_{name}"] = [
            {
                "x": x,
                "e_on_uJ": r.metrics["on_e_on"] * UJ,
                "e_off_uJ": r.metrics["off_e_off"] * UJ,
                "e_rr_uJ": r.metrics["on_e_rr"] * UJ,
            }
            for x, r in zip(xs, ok, strict=True)
        ]
    plots.panel_grid(
        [panels],
        f"{NOMINAL.device.part}: switching energy vs operating point (Rg = 4.5 Ohm, 30 nH)",
        FIGURES / "operating_point.png",
    )


def make_outputs(
    val_rows: list[Row],
    conv_rows: list[Row],
    sw: dict[str, tuple[Sweep, list[RunRecord]]],
) -> Row:
    dev = NOMINAL.device
    summary: Row = {
        "limits": {
            "v_peak_limit_V": V_PEAK_LIMIT_FRACTION * dev.vds_rating,
            "dv_dt_limit_V_per_ns": DVDT_LIMIT * VNS,
            "vth_min_V": dev.vth_min,
        }
    }
    m_nom = _nominal(summary)
    _convergence_figure(conv_rows)
    summary["convergence"] = conv_rows
    _validation_figure(val_rows)
    summary["validation"] = val_rows
    _rg_tradeoff(sw, summary)
    _stray_budget(sw, summary)
    _kelvin(sw, m_nom, summary)
    _operating_point(sw, summary)
    ok_vg = _ok(sw["vgs_off"][1])
    summary["vgs_off"] = [
        {
            "vgs_off": r.cfg.vgs_off,
            "vgs_hs_max": r.metrics["on_vgs_hs_max"],
            "margin": r.metrics["vgs_hs_margin"],
            "e_on_uJ": r.metrics["on_e_on"] * UJ,
            "e_off_uJ": r.metrics["off_e_off"] * UJ,
            "e_rr_uJ": r.metrics["on_e_rr"] * UJ,
            "vgs_hs_min": r.metrics["off_vgs_hs_min"],
        }
        for r in ok_vg
    ]
    summary["failed_runs"] = [r.cfg.key() for _, (_, recs) in sw.items() for r in recs if r.error]
    return summary


